var a = "20";
var b = "10";
// function to add two numbers
function add(x, y) {
    return x + y;
}
console.log(add(a, b)); // Output: "30" (string converted to numbers)
// function to subtract two numbers
function subtract(x, y) {
    return x - y;
}
console.log(subtract(a, b)); // Output: 10 (string converted to numbers)
// function to multiply two numbers
function multiply(x, y) {
    return x * y;
}
console.log(multiply(a, b)); // Output: 200 (string converted to numbers)
// function to divide two numbers
function divide(x, y) {
    return x / y;
}
console.log(divide(a, b)); // Output: 2 (string converted to numbers)   