# Program to demonstrate arithmetic operations in Python
# Define two numbers
num1 = 10
num2 = 89
# Perform arithmetic operations
addition = num1 + num2
subtraction = num2 -num1
multiplication = num1 * num2
division = num2 / num1
print(f"The sum of {num1} and {num2} is: {addition}")
print(f"The difference of {num2} and {num1} is: {subtraction}")
print(f"The product of {num1} and {num2} is: {multiplication}")
print(f"The quotient of {num2} and {num1} is: {division}")